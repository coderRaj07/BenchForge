-- Reviewed orders schema for the orders-mixed dataset.
-- BenchForge applies this file to an empty ephemeral database. It is not
-- accepted from an untrusted pull request as Terraform or shell.

CREATE TABLE customers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL,
    name text NOT NULL
);

CREATE TABLE products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku text NOT NULL,
    price_cents integer NOT NULL CHECK (price_cents > 0)
);

CREATE TABLE orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES customers (id),
    total_cents integer NOT NULL CHECK (total_cents > 0),
    status text NOT NULL CHECK (status IN ('created', 'paid', 'cancelled')),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX orders_customer_created_idx ON orders (customer_id, created_at DESC);

CREATE TABLE order_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES orders (id),
    product_id bigint NOT NULL REFERENCES products (id),
    qty integer NOT NULL CHECK (qty > 0),
    price_cents integer NOT NULL CHECK (price_cents > 0)
);

CREATE INDEX order_items_order_idx ON order_items (order_id);
